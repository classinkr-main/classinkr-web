/**
 * 워크플로 판정(JSON 배열)을 받아 결정론적으로 적용한다. (자동 분할 없음 — 오정렬 위험 회피)
 *  - 모든 문서: 소비자 카피(title/intro/stages/tips) + 단일 합성 이미지(heroImage) + 다운로드.
 *  - piiRegions: 패널 기준 분수좌표를 (rows×cols 균등 가정으로) 합성 전체 좌표로 환산해 블러 마스킹.
 *  - lib/cs-figma-enrichments.generated.ts 를 생성한다. (플래그십 523은 제외 — 큐레이션 우선)
 *
 * 입력: node scripts/cs-apply-rollout.mjs <judgmentsJsonPath>
 */
import sharp from "sharp"
import { readFile, writeFile } from "node:fs/promises"
import { existsSync } from "node:fs"
import path from "node:path"

const PUBLIC = "public"
const GENERATED = "lib/cs-figma-enrichments.generated.ts"
const SKIP_SLUGS = new Set(["cs-figma-digest-523"]) // 플래그십(큐레이션)

function decodeEntities(s) {
  return String(s ?? "")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#0?39;/g, "'")
    .replace(/&nbsp;/g, " ")
}

function srcToDisk(src) {
  return path.join(PUBLIC, src.replace(/^\//, ""))
}

const clamp = (v, max) => Math.max(0, Math.min(v, max))

function panelBoxFrac(rows, cols, panelIndex) {
  const idx = Math.max(0, (panelIndex || 1) - 1)
  const c = idx % Math.max(1, cols)
  const r = Math.floor(idx / Math.max(1, cols))
  return { x: c / Math.max(1, cols), y: r / Math.max(1, rows), w: 1 / Math.max(1, cols), h: 1 / Math.max(1, rows) }
}

async function maskComposite(file, regions, rows, cols) {
  if (!regions.length) return 0
  const meta = await sharp(file).metadata()
  const W = meta.width, H = meta.height
  const overlays = []
  for (const r of regions) {
    const pb = panelBoxFrac(rows, cols, r.panelIndex)
    const left = clamp(Math.round((pb.x + r.xFrac * pb.w) * W), W - 2)
    const top = clamp(Math.round((pb.y + r.yFrac * pb.h) * H), H - 2)
    const width = Math.max(2, Math.min(Math.round(r.wFrac * pb.w * W), W - left))
    const height = Math.max(2, Math.min(Math.round(r.hFrac * pb.h * H), H - top))
    const blurred = await sharp(file).extract({ left, top, width, height }).blur(24).toBuffer()
    overlays.push({ input: blurred, left, top })
  }
  const out = await sharp(file).composite(overlays).toBuffer()
  await sharp(out).toFile(file)
  return overlays.length
}

function buildEnrichment(j) {
  const stages = (j.stages || []).map((s) => ({ title: decodeEntities(s.title), body: decodeEntities(s.body) }))
  const e = {
    title: decodeEntities(j.consumerTitle),
    intro: decodeEntities(j.consumerIntro),
    stages,
    tips: (j.tips || []).map(decodeEntities),
  }
  if (j.hasImage && j.compositeSrc) {
    e.heroImage = { src: j.compositeSrc, alt: decodeEntities(j.consumerTitle) }
    e.downloadImage = {
      src: j.compositeSrc,
      label: "전체 안내 한 장으로 보기 (이미지 내려받기)",
      description: "단계별 화면을 한 장에 모았습니다. 인쇄하거나 저장해 두고 보세요.",
    }
  }
  return e
}

// CLI
const argv = process.argv.slice(2)
if (argv[0]) {
  const judgments = JSON.parse(await readFile(argv[0], "utf8"))
  const map = {}
  const report = []
  for (const j of judgments) {
    if (SKIP_SLUGS.has(j.slug)) { report.push({ slug: j.slug, action: "skip-curated" }); continue }
    try {
      if (!j.consumerTitle || !j.consumerIntro || !(j.stages || []).length) {
        report.push({ slug: j.slug, action: "no-copy" })
        continue
      }
      let masked = 0
      if (j.hasImage && j.compositeSrc) {
        const disk = srcToDisk(j.compositeSrc)
        if (existsSync(disk)) {
          masked = await maskComposite(disk, j.piiRegions || [], j.rows || 1, j.cols || 1)
        } else {
          report.push({ slug: j.slug, action: "missing-file", warning: disk })
        }
      }
      map[j.slug] = buildEnrichment(j)
      report.push({ slug: j.slug, action: j.hasImage ? "enriched+image" : "enriched-text", masked })
    } catch (e) {
      report.push({ slug: j.slug, action: "error", warning: String(e.message || e) })
      console.log(`${j.slug}: ERROR ${e.message}`)
    }
  }

  const ts = `// Generated by scripts/cs-apply-rollout.mjs from CS rollout workflow judgments.\n// Do not edit manually.\nimport type { CsFigmaEnrichment } from "@/lib/cs-figma-enrichments"\n\nexport const GENERATED_CS_FIGMA_ENRICHMENTS: Record<string, CsFigmaEnrichment> = ${JSON.stringify(map, null, 2)}\n`
  await writeFile(GENERATED, ts)
  await writeFile("/tmp/cs-apply-report.json", JSON.stringify(report, null, 2))

  const c = (a) => report.filter((r) => r.action === a).length
  const totalMasked = report.reduce((s, r) => s + (r.masked || 0), 0)
  console.log(`\nenriched+image=${c("enriched+image")} enriched-text=${c("enriched-text")} no-copy=${c("no-copy")} missing-file=${c("missing-file")} skip=${c("skip-curated")} error=${c("error")}; PII regions masked=${totalMasked}; entries=${Object.keys(map).length}`)
}
