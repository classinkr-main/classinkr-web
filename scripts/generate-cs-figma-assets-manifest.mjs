import { existsSync, readdirSync, writeFileSync } from "node:fs"
import { join, relative, sep } from "node:path"

const repoRoot = process.cwd()
const assetRoot = join(repoRoot, "public/docs/files/cs-figma")
const outputPath = join(repoRoot, "lib/cs-figma-assets.generated.ts")
const imageExtensions = new Set([".png", ".jpg", ".jpeg", ".webp", ".gif", ".avif"])

function listImageFiles(dir) {
  if (!existsSync(dir)) return []

  const files = []
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const fullPath = join(dir, entry.name)
    if (entry.isDirectory()) {
      files.push(...listImageFiles(fullPath))
      continue
    }

    const dotIndex = entry.name.lastIndexOf(".")
    const extension = dotIndex >= 0 ? entry.name.slice(dotIndex).toLowerCase() : ""
    if (imageExtensions.has(extension)) files.push(fullPath)
  }
  return files
}

const assetPaths = listImageFiles(assetRoot)
  .map((filePath) => `/${relative(join(repoRoot, "public"), filePath).split(sep).join("/")}`)
  .sort((left, right) => left.localeCompare(right, "ko-KR"))

const file = `// Generated by scripts/generate-cs-figma-assets-manifest.mjs.
// Do not edit manually; place images under public/docs/files/cs-figma and regenerate.

export const CS_FIGMA_ASSET_PATHS = ${JSON.stringify(assetPaths, null, 2)} satisfies string[]
`

writeFileSync(outputPath, file)
console.log(`Generated ${assetPaths.length} CS Figma asset paths at ${outputPath}`)
