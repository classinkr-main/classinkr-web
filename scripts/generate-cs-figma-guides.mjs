import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { createJiti } from "jiti"

const repoRoot = process.cwd()
const digestPath = join(repoRoot, "docs/active/cs-figma-board-digest-2026-06-21.md")
const outputPath = join(repoRoot, "lib/cs-figma-guides.generated.ts")

const jiti = createJiti(import.meta.url, {
  alias: {
    "@": repoRoot,
  },
})

const { buildCsFigmaGuideFromDigestEntry, parseCsFigmaDigestMarkdown } = await jiti.import(
  "../lib/cs-figma-digest.ts"
)

const digestMarkdown = readFileSync(digestPath, "utf8")
const guides = parseCsFigmaDigestMarkdown(digestMarkdown).map(buildCsFigmaGuideFromDigestEntry)

const file = `// Generated by scripts/generate-cs-figma-guides.mjs from docs/active/cs-figma-board-digest-2026-06-21.md.
// Do not edit manually; update the digest parser or source digest, then regenerate.

import type { CsFigmaGuide } from "@/lib/cs-figma-guides"

export const CS_FIGMA_DIGEST_GUIDES = ${JSON.stringify(guides, null, 2)} satisfies CsFigmaGuide[]
`

writeFileSync(outputPath, file)
console.log(`Generated ${guides.length} CS Figma digest guides at ${outputPath}`)
