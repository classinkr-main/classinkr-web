def hexes(color="rgba(255,255,255,.16)", accent="#FFE14D"):
    import math
    out = []
    r = 78
    w = math.sqrt(3) * r
    for row in range(6):
        for col in range(5):
            cx = 90 + col * w + (w / 2 if row % 2 else 0)
            cy = 90 + row * r * 1.5
            pts = " ".join(f"{cx + r * math.cos(math.radians(60 * k - 30)):.1f},{cy + r * math.sin(math.radians(60 * k - 30)):.1f}" for k in range(6))
            fill = accent if (row, col) in ((1, 2), (3, 3), (4, 1)) else "none"
            op = "1" if fill != "none" else ".9"
            out.append(f'<polygon points="{pts}" fill="{fill}" stroke="{color}" stroke-width="3" opacity="{op}"/>')
    return f'<svg class="hexes" viewBox="0 0 760 820" aria-hidden="true">{"".join(out)}</svg>'


