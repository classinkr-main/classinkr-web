/**
 * 첫 방문자가 한 줄로 묻는 '기본 사실' 질문의 정해 둔 답.
 * 회사·대표, 전자칠판 필수 여부, 지원 기기, 인원·보관 기간 같은 한도, 그리고 원가·고객사 이름처럼 답하지 않는 것까지 다룬다.
 *
 * 왜 따로 두나
 * - quick-answers-field.ts 의 답은 길고 구체적인 상황 질문에 맞춘 좁은 패턴이다. 그래서 "맥북에도 깔리나요?",
 *   "대표는 누구인가요?", "한 교실에 최대 몇 명?" 같은 한 줄 질문은 거기에 닿지 못하고 약한 문서 검색으로 빠져
 *   엉뚱한 문서 조각이나 되묻기가 나갔다(2026-11-13 점검: 첫 방문자 질문 180개 가운데 제대로 답한 것이 24%).
 *
 * 지키는 것 (quick-answers-field.ts 와 같다)
 * - 사실은 공개된 것만 쓴다: 공개 문서(lib/docs.ts, lib/docs-troubleshooting/*.ts, lib/classin-positioning.ts)와
 *   홈페이지에 이미 실린 내용(하단 회사 정보, 회사 소개 /about, 서비스 소개서 /introduction, 체크아웃, 개인정보처리방침).
 *   답마다 근거 문서(docPath)를 달고, 테스트(tests/chatbot/basics-quick-answers.test.ts)가 그 문서가 실제로 공개돼 있는지 본다.
 * - 문서에 없는 숫자·기간·가격·위치는 말하지 않는다. "공개 안내에 없다"고 밝히고 상담으로 넘긴다.
 * - 반대로 "공개 안내에 없다"고 쓰기 전에 도움말 문서만이 아니라 홈페이지의 다른 공개 페이지도 확인한다.
 *   (첫 초안은 본사 위치·지역 사례·결제 주기·부가세·설치비를 "없다"고 했는데 모두 /about·/introduction·체크아웃에 있었다.)
 * - 가격·할인·환불·복구를 약속하지 않는다. 아이디·전화번호·카드 번호를 채팅창에 적으라고 하지 않는다.
 * - 짧고 단순한 질문에만 쓴다(isPlainFactQuestion). 길거나 증상이 섞인 질문은 기존 정해 둔 답·증상 안내·문서 검색이 맡는다.
 * - 기존 정해 둔 답(quick-answers-field.ts, service.ts 의 buildServiceQuickAnswer)이 모두 빗나간 뒤에만 본다.
 * - handoff 를 달면 상담 버튼이 뜨고 담당자에게 알림이 간다. 견적·계약·서면 확인이 필요한 질문에만 단다.
 *
 * 정책으로 정해 둔 것
 * - 회사 국적: 회사 소개(/about) 페이지에 공개된 사무소 위치를 그대로 말한다(글로벌 HQ 싱가포르, EEO 본사·R&D 센터 베이징,
 *   한국 법인 서울 목동). "중국 회사다/아니다"로 이름 붙이지 않고, 서버 위치는 여전히 추측하지 않는다.
 * - 특정 학원의 사용 여부: 채팅에서 쓴다고도 안 쓴다고도 확인하지 않는다(그 학원의 정보).
 *   홈페이지에 공개된 도입 사례(/introduction/cases, 문서센터 고객 사례)를 직접 보도록 안내한다.
 * - 최대 인원: 도움말은 "요금제마다 다름"이고 소개 페이지에는 "최대 2,000명"이 있다. 소개 자료 기준임을 밝히고 함께 말한다.
 * - 금액: 체크아웃 화면에 금액이 보이는 항목(설치비 등)도 채팅에서는 숫자로 말하지 않는다. 어디서 확인하는지만 알린다.
 *
 * 항목 순서가 곧 우선순위다(첫 번째로 맞는 답을 쓴다). 두 가지를 함께 물은 질문에만 두 답을 잇는다.
 */

import type { FieldQuickAnswer } from "./quick-answers-field"

export interface BasicQuickAnswer extends FieldQuickAnswer {
  /**
   * 답의 근거가 되는 공개 문서 경로(/docs/<category>/<slug>).
   * 원가처럼 문서 근거 없이 정책으로 거절하는 답은 null.
   */
  docPath: string | null
  /** 출처에 붙일 섹션 이름. 없으면 "요약". */
  docHeading?: string
}

/** required 를 모두 만족하되 excluded 가운데 하나라도 맞으면 제외한다. */
const allBut =
  (required: RegExp[], excluded: RegExp[]) =>
  (text: string) =>
    required.every((pattern) => pattern.test(text)) && !excluded.some((pattern) => pattern.test(text))

// 공백을 뺀 길이. 첫 방문자의 기본 질문은 대부분 한 줄이다(점검한 180개 질문은 모두 37자 이하).
// 이보다 긴 질문은 상황 설명이 붙은 경우가 많아 기존 정해 둔 답·증상 안내·문서 검색에 맡긴다.
const PLAIN_QUESTION_MAX_LENGTH = 45

// 증상·장애 신호. "~하면 안 되나요?"는 허락을 묻는 말이라 증상이 아니다.
const TROUBLE_SIGNAL_RE =
  /(?<!면\s?)안\s*(?:돼|되|됨|됐|됩|나와|나옴|들려|보여|켜져|떠요|열려|먹)|(?<!면\s?)안돼|(?<!면\s?)안되|안됨|오류|에러|끊겨|끊김|튕겨|튕김|멈춰|멈춤|먹통|고장|이상해|이상하|실패|막혔|막혀|비활성|회색|눌러도|눌렀더니|뜹니다|라고\s*(?:떠|뜨|나와|나옵)|지원되지\s*않|했는데도|해\s*봐도|0\s*kb/

/** 기본 사실 답을 써도 되는 짧고 단순한 질문인지 본다. */
export function isPlainFactQuestion(text: string) {
  const compact = text.replace(/\s+/g, "")
  if (compact.length === 0 || compact.length > PLAIN_QUESTION_MAX_LENGTH) return false
  return !TROUBLE_SIGNAL_RE.test(text)
}

